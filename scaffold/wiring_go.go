package scaffold

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// GoWiringFile is the name of the file GenerateGoWiring's source is written to,
// in the output directory above the aggregates' packages.
const GoWiringFile = "register.go"

// GoWiring describes the package GenerateGoWiring writes: the output
// directory of `schema import --lang go`, seen as a package of the consumer's
// own module.
type GoWiring struct {
	// Package is the package name (the output directory's base name, made a
	// valid identifier).
	Package string
	// ImportBase is the output directory's import path (module path plus the
	// directory's path inside the module); each aggregate's package is
	// ImportBase/<GoPackageName(aggregate)>.
	ImportBase string
	// ModelFile is the copy of the document beside the generated file,
	// embedded into the program.
	ModelFile string
}

var goIdent = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

// GoWiringPackage makes a package name of a directory's base name: lower
// case, letters, digits and underscores; "domain" when nothing usable is left.
func GoWiringPackage(base string) string {
	name := strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '_':
			return r
		case r >= 'A' && r <= 'Z':
			return r + ('a' - 'A')
		}
		return -1
	}, base)
	if !goIdent.MatchString(name) {
		return "domain"
	}
	return name
}

// GenerateGoWiring writes the package that wires a document's generated Go
// domains into a program of one's own: what a hand-written main.go used to
// do from the importer's printed suggestions. It declares the read models'
// collections, registers every decider (protected when it carries personal
// data), projection, search and reactor, enforces the document's command
// permissions, and serves every read route. It names no source of messages
// (no schedule, URL or credential): those stay with surface tooling.
func GenerateGoWiring(w GoWiring, domains []Domain) (string, error) {
	if !goIdent.MatchString(w.Package) {
		return "", fmt.Errorf("wiring package name %q is not a Go identifier", w.Package)
	}
	if w.ImportBase == "" || w.ModelFile == "" {
		return "", fmt.Errorf("wiring needs an import path and a model file")
	}
	ds := append([]Domain(nil), domains...)
	sort.Slice(ds, func(i, j int) bool { return ds[i].Aggregate < ds[j].Aggregate })

	hasPII, hasSearch := false, false
	for _, d := range ds {
		hasPII = hasPII || len(d.PIIFields()) > 0
		for _, rm := range d.ReadModels {
			for _, f := range rm.Filters {
				hasSearch = hasSearch || f.Kind == FilterMatch
			}
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by pocketcqrs schema import --lang go. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// Package %s is the document %s compiled into a program of your own: its\n", w.Package, w.ModelFile)
	b.WriteString("// aggregates' packages below this directory, and the wiring that registers them\n")
	b.WriteString("// on pocketcqrs's host (docs/go-guide.md, \"Your own program\"):\n//\n")
	fmt.Fprintf(&b, "//\td := %s.New()\n", w.Package)
	b.WriteString("//\thost.Run(host.Options{Register: d.Register, Serve: d.Serve})\n//\n")
	b.WriteString("// Regenerate it (go generate) rather than editing it; what is your own goes in\n")
	b.WriteString("// your own files, around d.Register and d.Serve.\n")
	fmt.Fprintf(&b, "package %s\n\n", w.Package)

	imports := []string{`_ "embed"`}
	if hasSearch {
		imports = append(imports, `"fmt"`, `"os"`, `"path/filepath"`)
	}
	imports = append(imports, "", `"github.com/pocketbase/pocketbase/core"`, "",
		`"github.com/jamestryand/pocketcqrs/decider"`,
		`"github.com/jamestryand/pocketcqrs/emschema"`,
		`"github.com/jamestryand/pocketcqrs/host"`,
		`"github.com/jamestryand/pocketcqrs/pii"`,
		`"github.com/jamestryand/pocketcqrs/queryroute"`,
		`"github.com/jamestryand/pocketcqrs/searchindex"`, "")
	for _, d := range ds {
		pkg := GoPackageName(d.Aggregate)
		imports = append(imports, fmt.Sprintf("%s %q", pkg, w.ImportBase+"/"+pkg))
	}
	b.WriteString("import (\n")
	for _, imp := range imports {
		if imp == "" {
			b.WriteString("\n")
			continue
		}
		b.WriteString("\t" + imp + "\n")
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "//go:embed %s\nvar model []byte\n\n", w.ModelFile)
	b.WriteString("// Model is the document this package was generated from.\nfunc Model() []byte { return model }\n\n")

	b.WriteString("// Domain is the document's wiring. Its fields are set by Register.\ntype Domain struct {\n")
	b.WriteString("\t// PII is the personal-data wiring (nil when the document has no personal data).\n\tPII *pii.Deps\n")
	b.WriteString("\t// Indexes are the read models' searches, by collection.\n\tIndexes map[string]*searchindex.Index\n}\n\n")
	b.WriteString("// New returns the document's wiring, to hand to host.Options.\n")
	b.WriteString("func New() *Domain { return &Domain{Indexes: map[string]*searchindex.Index{}} }\n\n")

	b.WriteString("// Collections are the read models' collections.\nfunc Collections() []host.Collection {\n\treturn []host.Collection{\n")
	for _, d := range ds {
		for _, rm := range d.ReadModels {
			b.WriteString("\t\t" + goCollectionLiteral(rm) + ",\n")
			if rm.RowsPerListItem != nil {
				fmt.Fprintf(&b, "\t\t{Name: %q, Key: \"stream\", Fields: []host.Field{{Name: \"stream\", Type: \"text\"}, {Name: \"state\", Type: \"json\"}}},\n", ItemStreams(rm))
			}
		}
	}
	b.WriteString("\t}\n}\n\n")

	b.WriteString("// Register is host.Options.Register: collections, command permissions,\n")
	b.WriteString("// deciders, projections, searches and reactors.\n")
	b.WriteString("func (d *Domain) Register(h *host.Host) error {\n")
	b.WriteString("\tdoc, err := emschema.Parse(\"" + w.ModelFile + "\", model)\n\tif err != nil {\n\t\treturn err\n\t}\n")
	b.WriteString("\t// who may send each command, and who may ask for an erasure, as the document says\n")
	b.WriteString("\tif err := h.DeclareCommands(doc); err != nil {\n\t\treturn err\n\t}\n")
	b.WriteString("\tif err := h.EnsureCollections(Collections()...); err != nil {\n\t\treturn err\n\t}\n")
	if hasPII {
		b.WriteString("\t// personal data: needs KMS_FACADE_URL (the key service)\n")
		b.WriteString("\tdeps, err := h.WirePII()\n\tif err != nil {\n\t\treturn err\n\t}\n\td.PII = &deps\n")
	} else {
		b.WriteString("\tvar deps pii.Deps\n\t_ = deps\n")
	}
	for _, d := range ds {
		pkg := GoPackageName(d.Aggregate)
		ctor := ExportName(d.Aggregate)
		if len(d.PIIFields()) > 0 {
			fmt.Fprintf(&b, "\tdecider.RegisterProtected(h.Registry, %q, %s.%s(), %s.NewProtector(deps))\n", d.Aggregate, pkg, ctor, pkg)
		} else {
			fmt.Fprintf(&b, "\tdecider.Register(h.Registry, %q, %s.%s())\n", d.Aggregate, pkg, ctor)
		}
		for _, rm := range d.ReadModels {
			fmt.Fprintf(&b, "\th.AddProjection(%s.New%s(h.App))\n", pkg, ExportName(rm.Collection))
		}
		for _, r := range d.Reactors {
			fmt.Fprintf(&b, "\th.AddReactor(%s.%s())\n", pkg, ExportName(r.Name))
		}
	}
	if hasSearch {
		b.WriteString("\n\t// searches by a personal field: a keyed hash of it in search.db (rebuilt from\n")
		b.WriteString("\t// the log; leave it out of backups), keyed by the key service's index key\n")
		b.WriteString("\tindexKey := os.Getenv(searchindex.EnvIndexKey)\n\tif indexKey == \"\" {\n")
		b.WriteString("\t\treturn fmt.Errorf(\"%s is not set: the document's searches need the key service's index key name\", searchindex.EnvIndexKey)\n\t}\n")
		b.WriteString("\tstore, err := searchindex.Open(filepath.Join(h.DataDir, \"search.db\"))\n\tif err != nil {\n\t\treturn err\n\t}\n")
		b.WriteString("\th.OnClose(store)\n\tif _, err := store.PurgeErased(h.Context, deps.KMS); err != nil {\n\t\treturn err\n\t}\n")
		for _, d := range ds {
			pkg := GoPackageName(d.Aggregate)
			for _, rm := range d.ReadModels {
				for _, f := range rm.Filters {
					if f.Kind == FilterMatch {
						fmt.Fprintf(&b, "\tif d.Indexes[%q], err = searchindex.Register(h.Context, h.Engine, store, %s.%s, &deps, indexKey); err != nil {\n\t\treturn err\n\t}\n",
							rm.Collection, pkg, SearchSpecName(rm))
						break
					}
				}
			}
		}
	}
	b.WriteString("\treturn nil\n}\n\n")

	b.WriteString("// Serve is host.Options.Serve: every read model's read route\n")
	b.WriteString("// (GET /api/cqrs/rm/{collection}), checking the role the document gives it.\n")
	b.WriteString("func (d *Domain) Serve(se *core.ServeEvent, h *host.Host) error {\n")
	readModels := 0
	for _, d := range ds {
		readModels += len(d.ReadModels)
	}
	if readModels == 0 {
		b.WriteString("\t_ = queryroute.Config{} // the document has no read models\n")
	} else {
		b.WriteString("\tcfg := queryroute.Config{PII: d.PII, ResolveOwnRole: h.OwnRole, SubjectOf: h.OwnSubjectID, Indexes: d.Indexes,\n")
		b.WriteString("\t\tLogger: func(msg string, args ...any) { se.App.Logger().Warn(msg, args...) }}\n")
	}
	for _, d := range ds {
		pkg := GoPackageName(d.Aggregate)
		for _, rm := range d.ReadModels {
			fmt.Fprintf(&b, "\tif err := queryroute.Register(se, %s.%s, cfg); err != nil {\n\t\treturn err\n\t}\n", pkg, QuerySpecName(rm))
		}
	}
	b.WriteString("\treturn nil\n}\n")
	return formatGo(b.String())
}

// goCollectionLiteral is a read model's host.Collection literal: the key
// column first (text), then the declared fields in their storage types.
func goCollectionLiteral(rm ReadModel) string {
	fields := []string{fmt.Sprintf("{Name: %q, Type: \"text\"}", rm.Key)}
	for _, f := range rm.Fields {
		if f.Name == rm.Key {
			continue
		}
		typ := StorageType(f)
		if f.PII {
			typ = "text" // the encrypted envelope
		}
		fields = append(fields, fmt.Sprintf("{Name: %q, Type: %q}", f.Name, typ))
	}
	return fmt.Sprintf("{Name: %q, Key: %q, Fields: []host.Field{%s}}", rm.Collection, rm.Key, strings.Join(fields, ", "))
}
